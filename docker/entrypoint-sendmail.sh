#!/bin/sh
# =============================================================================
# entrypoint.sh – configure sendmail + MIMEDefang from environment variables
# =============================================================================
set -e

log() { echo "[entrypoint] $*"; }

# ---------------------------------------------------------------------------
# Timezone
# ---------------------------------------------------------------------------
if [ -n "${TZ}" ] && [ -f "/usr/share/zoneinfo/${TZ}" ]; then
    ln -sf "/usr/share/zoneinfo/${TZ}" /etc/localtime
    echo "${TZ}" > /etc/timezone
fi

# ---------------------------------------------------------------------------
# If no custom filter is bind-mounted, fall back to the shipped default
# ---------------------------------------------------------------------------
if [ ! -s /etc/mail/mimedefang-filter ]; then
    log "No filter mounted at /etc/mail/mimedefang-filter – using default"
    cp /etc/mail/mimedefang-filter.default /etc/mail/mimedefang-filter
fi
chmod 644 /etc/mail/mimedefang-filter

# ---------------------------------------------------------------------------
# Generate sendmail.mc from environment variables (unless custom one mounted)
# ---------------------------------------------------------------------------
SENDMAIL_MC=/etc/mail/sendmail.mc

if [ ! -s "${SENDMAIL_MC}" ]; then
    log "Generating ${SENDMAIL_MC} for domain=${MAIL_DOMAIN} host=${MAIL_HOST}"
    cat > "${SENDMAIL_MC}" <<MC
divert(-1)dnl
dnl Generated by MIMEDefang container entrypoint – do not edit by hand.
dnl Mount /etc/mail/sendmail.mc to override entirely.
divert(0)dnl
include(\`/usr/share/sendmail-cf/m4/cf.m4')dnl
VERSIONID(\`mimedefang-docker')dnl
OSTYPE(\`linux')dnl
DOMAIN(\`generic')dnl
define(\`confDOMAIN_NAME', \`${MAIL_HOST}')dnl
define(\`confMAX_MESSAGE_SIZE', \`52428800')dnl
define(\`confLOG_LEVEL', \`${LOG_LEVEL}')dnl
define(\`confSMTP_LOGIN_MSG', \`\$j Sendmail; \$b')dnl
FEATURE(\`use_cw_file')dnl
FEATURE(\`use_ct_file')dnl
FEATURE(\`local_procmail', \`', \`procmail -t -Y -a \$h -d \$u')dnl
FEATURE(\`accept_unresolvable_domains')dnl
FEATURE(\`blacklist_recipients')dnl
dnl --- MIMEDefang milter ---
INPUT_MAIL_FILTER(\`mimedefang', \`S=unix:${SPOOL_DIR}/mimedefang.sock, F=T, T=S:360s;R:360s;E:15m')dnl
define(\`confMILTER_MACROS_CONNECT', \`b, j, _, {daemon_name}, {if_name}, {if_addr}')dnl
define(\`confMILTER_MACROS_ENVFROM', \`i, {auth_authen}')dnl
define(\`confMILTER_MACROS_ENVRCPT', \`{rcpt_mailer}, {rcpt_host}, {rcpt_addr}')dnl
MC

    # Optional smart host relay
    if [ -n "${SMART_HOST}" ]; then
        echo "define(\`SMART_HOST', \`${SMART_HOST}')dnl" >> "${SENDMAIL_MC}"
    fi

    # Optional submission port 587
    if [ "${ENABLE_SUBMISSION}" = "yes" ]; then
        cat >> "${SENDMAIL_MC}" <<MC
DAEMON_OPTIONS(\`Port=submission, Name=MSA, M=Ea')dnl
MC
    fi

    cat >> "${SENDMAIL_MC}" <<MC
MAILER(\`local')dnl
MAILER(\`smtp')dnl
MC
fi

# Rebuild sendmail.cf
log "Compiling sendmail.cf"
m4 "${SENDMAIL_MC}" > /etc/mail/sendmail.cf

# local-host-names
echo "${MAIL_DOMAIN}"  > /etc/mail/local-host-names
echo "${MAIL_HOST}"   >> /etc/mail/local-host-names
echo "localhost"      >> /etc/mail/local-host-names

# ---------------------------------------------------------------------------
# Spool / quarantine directories
# ---------------------------------------------------------------------------
mkdir -p "${SPOOL_DIR}" /var/spool/MD-Quarantine /run/mimedefang
# Try to own them as defang; harmless if user doesn't exist in base image
chown defang:defang "${SPOOL_DIR}" /var/spool/MD-Quarantine /run/mimedefang 2>/dev/null || true
chmod 700 "${SPOOL_DIR}" /var/spool/MD-Quarantine

# ---------------------------------------------------------------------------
# Start rsyslog so MIMEDefang / sendmail can log
# ---------------------------------------------------------------------------
rsyslogd

# ---------------------------------------------------------------------------
# Start MIMEDefang multiplexor
# ---------------------------------------------------------------------------
log "Starting mimedefang-multiplexor (min=${MIN_WORKERS} max=${MAX_WORKERS} idle=${MAX_IDLE})"
/usr/local/bin/mimedefang-multiplexor \
    -p "${SPOOL_DIR}/mimedefang-multiplexor.sock" \
    -o "${SPOOL_DIR}/mimedefang-multiplexor.lock" \
    -m "${MIN_WORKERS}" \
    -x "${MAX_WORKERS}" \
    -i "${MAX_IDLE}" \
    -z "${SPOOL_DIR}" \
    -l &

sleep 1   # give the multiplexor a moment to bind its socket

# ---------------------------------------------------------------------------
# Start MIMEDefang (milter bridge)
# ---------------------------------------------------------------------------
log "Starting mimedefang"
rm -f "${SPOOL_DIR}/mimedefang.sock"
/usr/local/bin/mimedefang \
    -p "${SPOOL_DIR}/mimedefang.sock" \
    -m "${SPOOL_DIR}/mimedefang-multiplexor.sock" \
    -z "${SPOOL_DIR}" &

sleep 1

# ---------------------------------------------------------------------------
# Start sendmail (foreground so Docker sees the PID)
# ---------------------------------------------------------------------------
log "Starting sendmail (port ${SMTP_PORT}, domain ${MAIL_DOMAIN})"
exec /usr/sbin/sendmail -bd -q15m -L sm-mta
